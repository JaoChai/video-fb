// เรียงจากยาวไปสั้นเสมอ เพราะ strings.NewReplacer เทียบตามลำดับ argument —
// คำประกอบต้องมาก่อนคำย่อย (ไอดีแอดส์แวนซ์ ก่อน แอดส์แวนซ์ และ ไอดี)
