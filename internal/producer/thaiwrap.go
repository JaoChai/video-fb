// loanWordGuard สร้างครั้งเดียวตอนโหลดแพ็กเกจ. Replacer สแกนซ้ายไปขวาแบบไม่ทับซ้อน
// และเทียบคำตามลำดับที่ส่งเข้ามา ซึ่งตรงกับกติกา "คำยาวชนะคำสั้น" ที่รายการถืออยู่แล้ว
var loanWordGuard = newLoanWordGuard()

func newLoanWordGuard() *strings.Replacer {
	pairs := make([]string, 0, len(thaiLoanWords)*2)
	for _, w := range thaiLoanWords {
		pairs = append(pairs, w, zwsp+w+zwsp)
	}
	return strings.NewReplacer(pairs...)
}

// GuardLoanWords แทรก zwsp คร่อมทุกคำในรายการที่พบในสตริง เพื่อบังคับให้ Chromium
// ขึ้นบรรทัดที่ขอบคำจริงแทนที่จะเดาเอง.
//
// ล้าง zwsp เดิมทิ้งก่อนเสมอ ทำให้เรียกซ้ำได้โดยไม่สะสมอักขระ — ระบบไม่ได้ใช้ zwsp
// เพื่อจุดประสงค์อื่น การล้างจึงปลอดภัย.
func GuardLoanWords(s string) string {
	return loanWordGuard.Replace(strings.ReplaceAll(s, zwsp, ""))
}
