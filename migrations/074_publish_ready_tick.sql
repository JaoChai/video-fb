-- 074: ให้รอบส่งคลิปมี schedule ของตัวเอง (แก้บั๊กคิว publish ค้างถาวร)
--
-- อาการ: คลิปที่ไม่ทันรอบส่งของตัวเองจะค้างสถานะ ready ไปเรื่อยๆ ไม่มีวันตามทัน
-- เพราะ PublishReady หยิบทีละ 1 คลิป (LIMIT 1) และถูกเรียก "เฉพาะตอนท้ายรอบผลิต"
-- เท่านั้น — ผลิต 1 ส่ง 1 พอสะดุดรอบเดียวคิวก็เลื่อนค้างตลอดกาล เกิดจริงเมื่อ
-- 28 ก.ค. (กด stop ตอน 18:07 → คลิปตกรอบ → รอบ 21:00 หยิบตัวเก่าไป ตัวใหม่ค้าง)
--
-- handlerFor map action 'publish_daily' ไป PublishReady อยู่แล้ว จึงไม่ต้องแก้โค้ด
-- scheduler เลย แค่มีแถว schedule ที่เปิดอยู่ + เปลี่ยนเป็นรายชั่วโมง · ยังส่งทีละ
-- 1 คลิปเหมือนเดิม (ไม่เทคิวรวดเดียว) แต่มีจังหวะส่ง 24 ครั้ง/วัน เทียบกับคลิปที่
-- ผลิตจริง 4 ตัว/วัน คิวจึงไล่ทันเสมอ
--
-- ตั้งที่นาทีที่ 30 ไม่ใช่นาทีที่ 0 เพราะรอบผลิตทุกตัวยิงตอนนาที 0 (12/15/18/21:00)
-- แล้วขั้น publish ท้ายรอบผลิตจะตกราวนาทีที่ 8-11 — :30 จึงไม่ทับกับใครเลย
--
-- ยังต้องมาคู่กับ pg_try_advisory_lock ใน PublishReady (publisher.go) อยู่ดี เพราะ
-- รอบผลิตที่ยาวผิดปกติหรือการกดปุ่ม publish เองยังชนกับ tick นี้ได้ ถ้าไม่มีล็อกจะ
-- อัปคลิปเดียวกันขึ้น YouTube ซ้ำ (การโพสต์เกิดก่อน UPDATE status เสมอ)
--
-- เลือกรายชั่วโมงแทนทุก 15 นาทีเพราะ auto_review อนุมัติคลิปเองได้ (ไม่ต้องมีคน)
-- ยิ่งรอบส่งถี่ ช่วงเวลาที่คนจะเข้ามาเบรกคลิปที่อนุมัติผิดยิ่งสั้น และคลิปที่ขึ้น
-- YouTube แล้วเอากลับไม่ได้ — ระบบไม่มีคำสั่งลบ/ซ่อนวิดีโอ
--
-- ต้อง UPDATE + INSERT ทั้งคู่: prod มีแถวนี้อยู่ (ถูกสร้างมือนอก migration, ปิดไว้
-- ตั้งแต่ 3 พ.ค.) แต่ 007 สั่ง DELETE แถว publish_daily ทิ้งและไม่มีไฟล์ไหนใส่คืน
-- ⇒ DB ที่สร้างใหม่จากไฟล์ migration ล้วนจะไม่มีแถวนี้ ถ้าเขียนแค่ UPDATE จะแมตช์
-- 0 แถวแบบเงียบๆ แล้วรอบส่งไม่เกิดขึ้นเลยทั้งที่ migration รายงานว่าสำเร็จ
--
-- idempotent: UPDATE ระบุ action ชัด + INSERT มี WHERE NOT EXISTS (แพตเทิร์นเดียว
-- กับ 032/037/042/045/066/071) รันซ้ำได้ผลเท่าเดิม
-- RunMigrations ไม่หุ้ม transaction ให้ — ต้อง BEGIN/COMMIT เอง

BEGIN;

UPDATE schedules
SET name            = 'Publish Ready',
    cron_expression = '30 * * * *',
    enabled         = TRUE
WHERE action = 'publish_daily';

INSERT INTO schedules (name, cron_expression, action, enabled)
SELECT 'Publish Ready', '30 * * * *', 'publish_daily', TRUE
WHERE NOT EXISTS (SELECT 1 FROM schedules WHERE action = 'publish_daily');

COMMIT;
